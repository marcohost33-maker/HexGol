import { readFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { resolve } from "node:path";
import { describe, expect, it } from "vitest";
import {
  buildPlanarGoldenV1,
  canonicalJson,
  SOURCE_ENGINE_BLOB,
} from "../../scripts/generate-planar-golden.mjs";

const fixturePath = resolve("contracts/golhex-planar-golden-v1.json");
const committed = readFileSync(fixturePath, "utf8");
const parsed = JSON.parse(committed);

describe("cross-repo planar Golden Vector contract", () => {
  it("is byte-for-byte generated by the production HexGol engine", () => {
    expect(canonicalJson(buildPlanarGoldenV1())).toBe(committed);
  });

  it("pins exact engine provenance and a stable contract checksum", () => {
    expect(parsed.schema).toBe("golhex-planar-golden-v1");
    expect(parsed.source.engineBlobSha).toBe(SOURCE_ENGINE_BLOB);
    const currentBlob = execFileSync(
      "git",
      ["hash-object", "src/lib/sim-engine.js"],
      { encoding: "utf8", cwd: resolve(".") },
    ).trim();
    expect(currentBlob).toBe(SOURCE_ENGINE_BLOB);
    expect(createHash("sha256").update(committed).digest("hex"))
      .toBe("c4c3b1d9ae0d25bddcbce8e41f666e1f4814a9be33fea0bee96f3a2954a7b5b1");
  });

  it("keeps the Offscreen worker on the same production transition core", () => {
    const worker = readFileSync("src/worker/render-worker.js", "utf8");
    expect(worker).toContain("stepLife as stepLifeCore");
    expect(worker).toMatch(/stepLifeCore\(\{/);
    expect(worker).not.toMatch(/function\s+stepLife\s*\(/);
  });

  it("records ADR-001-style R3 provenance for every checkpoint", () => {
    expect(parsed.provenance.reproducibilityLevel).toBe("R3-within-nodejs-backend");
    expect(parsed.provenance.canonicalReferenceBackend).toMatchObject({
      runtime: "Node.js",
      version: "22.23.2",
      npm: "10.9.8",
    });
    expect(parsed.provenance.precision).toEqual({
      col: "uint8",
      age: "uint16",
      ghost: "uint8",
      neighborCounts: "integer",
    });
    expect(parsed.provenance.seed).toBeNull();
    expect(parsed.provenance.tickSequence).toEqual([0,1,2,3,4,5]);
    expect(parsed.provenance.checkpointStateSha256).toHaveLength(6);
    for (const entry of parsed.provenance.checkpointStateSha256) {
      expect(entry.sha256).toMatch(/^[0-9a-f]{64}$/);
    }
  });

  it("contains topology plus every intermediate state, not only an end hash", () => {
    expect(parsed.topology.neighborTable).toHaveLength(5 * 6 * 6);
    expect(parsed.checkpoints.map((x) => x.tick)).toEqual([0,1,2,3,4,5]);
    for (const cp of parsed.checkpoints) {
      expect(cp.col).toHaveLength(30);
      expect(cp.age).toHaveLength(30);
      expect(cp.ghost).toHaveLength(30);
    }
  });
});
