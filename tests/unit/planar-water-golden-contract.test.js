import { readFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { join, resolve } from "node:path";
import { describe, expect, it } from "vitest";
import {
  buildProfile,
  canonicalJson,
  SOURCE_ENGINE_BLOB,
  stateSha256,
  WATER_PROFILES,
} from "../../scripts/generate-planar-water-golden.mjs";

// Upstream water Golden Vectors for golhex-3d (R03 re-audit 2026-11-19, NR-GH3D-R03-03:
// "source mirroring is not an independent 2D parity").
const SHA256 = {
  "water-oddr-edge": "ded5baa8b357f8e9d75d6aaf53937b6b108b62ef135b906b2e0ab0678c42f62e",
  "water-oddr-torus": "0c81bc141a2c43b8ac6c715f49c2ff9b3856ca41b24e38d7bb59d6d663140206",
};
const dir = resolve("contracts/golhex-planar-water-golden-v1");
const toFloat = (bits) => new Float32Array(new Uint32Array([bits]).buffer)[0];

describe("cross-repo planar water Golden Vector contract v1", () => {
  it("has exactly the reviewed profile rows", () => {
    expect(WATER_PROFILES.map((p) => p.id).sort()).toEqual(Object.keys(SHA256).sort());
  });

  for (const spec of WATER_PROFILES) {
    const committed = readFileSync(join(dir, `${spec.id}.json`), "utf8");
    const parsed = JSON.parse(committed);

    it(`${spec.id}: is byte-for-byte generated by the production engine and pinned`, () => {
      expect(canonicalJson(buildProfile(spec))).toBe(committed);
      expect(createHash("sha256").update(committed).digest("hex")).toBe(SHA256[spec.id]);
      expect(parsed.schema).toBe("golhex-planar-water-golden-v1");
      expect(parsed.source.engineFunction).toBe("stepWater");
      expect(parsed.source.engineBlobSha).toBe(SOURCE_ENGINE_BLOB);
      const blob = execFileSync("git", ["hash-object", "src/lib/sim-engine.js"], { encoding: "utf8", cwd: resolve(".") }).trim();
      expect(blob).toBe(SOURCE_ENGINE_BLOB);
    });

    it(`${spec.id}: checkpoints are lossless binary32 states whose hashes recompute`, () => {
      expect(parsed.checkpoints.map((cp) => cp.tick)).toEqual(parsed.provenance.tickSequence);
      for (const cp of parsed.checkpoints) {
        expect(cp.wBits).toHaveLength(spec.rows * spec.cols);
        expect(stateSha256(cp.tick, cp.wBits)).toBe(cp.stateSha256);
        for (const bits of cp.wBits) {
          expect(Number.isInteger(bits) && bits >= 0 && bits <= 0xffffffff).toBe(true);
          const v = toFloat(bits);
          expect(v >= 0 && v <= 1).toBe(true); // also rejects NaN
        }
      }
      // The seed in the fixture is the state at tick 0.
      const seeded = new Float32Array(spec.rows * spec.cols);
      for (const [r, c, v] of parsed.initial.cells) seeded[r * spec.cols + c] = v;
      expect(parsed.checkpoints[0].wBits.map(toFloat)).toEqual(Array.from(seeded));
    });

    it(`${spec.id}: the run is not trivial and stays closed`, () => {
      const hashes = new Set(parsed.checkpoints.map((cp) => cp.stateSha256));
      expect(hashes.size).toBe(parsed.checkpoints.length); // the field moves every tick
      expect(parsed.maxMassDriftFloat64).toBeLessThan(1e-5);
    });

    it(`${spec.id}: carries a counterexample that diverges from the contrast profile`, () => {
      const t = parsed.counterexample.firstDivergingTick;
      expect(t).toBeGreaterThan(0);
      expect(parsed.checkpoints[t].stateSha256).not.toBe(parsed.counterexample.stateSha256AtFirstDivergingTick);
      expect(parsed.counterexample.changes).toBe(spec.contrast.kind);
    });
  }

  it("covers both contrast kinds (binary32 store rounding and boundary)", () => {
    expect(WATER_PROFILES.map((p) => p.contrast.kind).sort()).toEqual(["boundary", "precision"]);
  });

  it("leaves the life contracts v1 and v2 untouched", () => {
    const pinned = {
      "contracts/golhex-planar-golden-v1.json": "c4c3b1d9ae0d25bddcbce8e41f666e1f4814a9be33fea0bee96f3a2954a7b5b1",
      "contracts/golhex-planar-golden-v2/b2s35-oddr-edge.json": "d35fad532432814224d96c0a608a1870803da341ded295f82231fa0e732e1a37",
      "contracts/golhex-planar-golden-v2/b2s34-oddr-torus.json": "6e590f6543e136eb7509b60b2fe0ab82fb8df752f7bbd6bd2761042bb1b0f85a",
    };
    for (const [file, sha] of Object.entries(pinned)) {
      expect(createHash("sha256").update(readFileSync(file)).digest("hex")).toBe(sha);
    }
  });
});
