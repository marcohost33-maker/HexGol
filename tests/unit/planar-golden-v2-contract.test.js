import { readFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { join, resolve } from "node:path";
import { describe, expect, it } from "vitest";
import {
  buildProfile,
  canonicalJson,
  PROFILES_V2,
  SOURCE_ENGINE_BLOB,
} from "../../scripts/generate-planar-golden-v2.mjs";

// golhex-3d Issue #22, stages 1 (second totalistic rule) and 2 (box-torus).
const SHA256 = {
  "b2s35-oddr-edge": "d35fad532432814224d96c0a608a1870803da341ded295f82231fa0e732e1a37",
  "b2s34-oddr-torus": "6e590f6543e136eb7509b60b2fe0ab82fb8df752f7bbd6bd2761042bb1b0f85a",
};
const dir = resolve("contracts/golhex-planar-golden-v2");

describe("cross-repo planar Golden Vector contract v2 (profile matrix)", () => {
  it("has exactly the reviewed profile rows", () => {
    expect(PROFILES_V2.map((p) => p.id).sort()).toEqual(Object.keys(SHA256).sort());
  });

  for (const spec of PROFILES_V2) {
    const committed = readFileSync(join(dir, `${spec.id}.json`), "utf8");
    const parsed = JSON.parse(committed);

    it(`${spec.id}: is byte-for-byte generated by the production engine and pinned`, () => {
      expect(canonicalJson(buildProfile(spec))).toBe(committed);
      expect(createHash("sha256").update(committed).digest("hex")).toBe(SHA256[spec.id]);
      expect(parsed.schema).toBe("golhex-planar-golden-v2");
      expect(parsed.source.engineBlobSha).toBe(SOURCE_ENGINE_BLOB);
      const blob = execFileSync("git", ["hash-object", "src/lib/sim-engine.js"], { encoding: "utf8", cwd: resolve(".") }).trim();
      expect(blob).toBe(SOURCE_ENGINE_BLOB);
    });

    it(`${spec.id}: carries a counterexample that diverges from the contrast profile`, () => {
      expect(parsed.counterexample.firstDivergingTick).toBeGreaterThan(0);
      const cp = parsed.provenance.checkpointStateSha256[parsed.counterexample.firstDivergingTick];
      expect(cp.sha256).not.toBe(parsed.counterexample.stateSha256AtFirstDivergingTick);
      if (parsed.counterexample.changes === "rule") {
        expect(parsed.exercisedLiveNeighbourCounts).toEqual(expect.arrayContaining([4, 5]));
      }
    });
  }

  it("leaves v1 untouched (no silent regeneration of an old contract version)", () => {
    const v1 = readFileSync("contracts/golhex-planar-golden-v1.json");
    expect(createHash("sha256").update(v1).digest("hex"))
      .toBe("c4c3b1d9ae0d25bddcbce8e41f666e1f4814a9be33fea0bee96f3a2954a7b5b1");
  });
});
